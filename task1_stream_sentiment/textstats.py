_WORD = re.compile(r"[а-яё]{4,}", re.IGNORECASE)


def top_words(texts, n: int = 15) -> list[tuple[str, int]]:
    counter = Counter()
    for t in texts:
        words = {w for w in _WORD.findall(str(t).lower()) if w not in STOPWORDS}
        counter.update(words)  # слово считаем один раз на отзыв
    return counter.most_common(n)
